import fs from 'node:fs';
const {LuauState}=await import(process.env.LUAU_WEB_ENTRY || 'luau-web');
const root=new URL('../',import.meta.url);
const read=name=>fs.readFileSync(new URL(name,root),'utf8');
const state=await LuauState.createAsync();
const patch=read('correccion-caras/PEGAR_CORREGIR_CARAS.txt');
state.loadstring(patch,'face_fix_installer',true);
let harness=read('validacion/installer-harness.luau');
harness=harness.slice(0,harness.indexOf('\ndo\n local svc'));
harness=harness.replace('return self.ClassName==class or class=="BaseScript"', 'return self.ClassName==class or (class=="LuaSourceContainer" and (self.ClassName=="ModuleScript" or self.ClassName=="Script" or self.ClassName=="LocalScript")) or class=="BaseScript"');
harness=harness.replace('__RUN_INSTALLER__',read('PEGAR_HISTORIA_MARCOS.txt')).replace('__RUN_RESTORE__',read('VOLVER_HISTORIA_ANTERIOR.txt'));
const checks=read('validacion/face-fix-checks.luau');
const [summary,merged]=await state.loadstring(harness+'\nlocal function faceFix()\n'+patch+'\nend\n'+checks,'face_patch_transactions',true)();
console.log(summary);
state.loadstring(merged,'merged_interpretation_preserving_existing_poses',true);
console.log('Compilation PASS: patched module with existing gesture adjustment.');
const raster=read('validacion/face-pixel-checks.luau');
console.log(await state.loadstring('local B=(function()\n'+read('Interpretacion.luau')+'\nend)()\n'+raster,'face_pixel_checks',true)());
state.destroy();
